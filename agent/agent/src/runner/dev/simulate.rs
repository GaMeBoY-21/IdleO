//! The services, simulated (`--simulate <kind>` in a development template's arguments): what each
//! writes to its log as it runs, and the outputs it leaves, so a local stack looks and behaves like the
//! real thing. Development only, like the rest of the development runner; nothing here runs a model.
//!
//! Every line and every output byte is generated: from the parameters, the input's size and line count,
//! and the session's id, never from a real model. A kind's log is a schedule over the job's
//! whole duration, so an attempt resumed from a checkpoint carries on where the last one stopped.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::str::FromStr;
use std::time::Duration;

use sha2::{Digest, Sha256};

/// A simulated service, named as the service is in the catalog.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum Kind {
    FineTune,
    RunCode,
}

impl FromStr for Kind {
    type Err = String;

    fn from_str(value: &str) -> Result<Self, Self::Err> {
        match value {
            "fine-tune" => Ok(Self::FineTune),
            "run-code" => Ok(Self::RunCode),
            _ => Err(format!("--simulate {value} isn't a kind: fine-tune or run-code")),
        }
    }
}

/// What the job was given that shapes its simulation.
#[derive(Debug, Clone)]
pub(super) struct Given {
    /// Every `SESSION_PARAM_*` variable, by its full name.
    pub params: BTreeMap<String, String>,
    /// The staged input's name, if there's one.
    pub input_name: Option<String>,
    pub input_bytes: u64,
    /// Lines in the input: training examples in a JSONL file.
    pub input_lines: u64,
}

/// One simulated job.
#[derive(Debug, Clone)]
pub(super) struct Simulation {
    kind: Kind,
    given: Given,
    /// Seeds every generated byte: the same session always gets the same outputs.
    seed: [u8; 32],
}

/// Training steps per epoch, at most; fewer for a small file (8 examples a step).
const MAX_STEPS_PER_EPOCH: u64 = 24;
const RUN_CODE_BATCHES: u64 = 16;
/// A `LoRA` adapter's simulated hidden size, which keeps the adapter file small.
const HIDDEN: usize = 64;

impl Simulation {
    pub(super) fn new(kind: Kind, given: Given, session_id: &str) -> Self {
        let seed = Sha256::digest(format!("{session_id} {kind:?}").as_bytes()).into();
        Self { kind, given, seed }
    }

    fn param(&self, name: &str, default: &str) -> String {
        self.given.params.get(&format!("SESSION_PARAM_{name}")).cloned().unwrap_or_else(|| default.to_owned())
    }

    fn number(&self, name: &str, default: u64, min: u64, max: u64) -> u64 {
        self.param(name, "").parse().unwrap_or(default).clamp(min, max)
    }

    fn input(&self) -> String {
        self.given.input_name.clone().unwrap_or_else(|| "no input".to_owned())
    }

    /// What every attempt prints before its work starts, a resumed one included.
    pub(super) fn opening(&self) -> Vec<String> {
        let input = self.input();
        match self.kind {
            Kind::FineTune => vec![
                format!("loading base model {} (4-bit)", self.param("BASE_MODEL", "Qwen2.5 0.5B Instruct")),
                format!(
                    "{input}: {} training examples, {} steps an epoch at batch size 8",
                    self.given.input_lines,
                    self.steps_per_epoch()
                ),
                format!(
                    "LoRA rank {}, alpha {}, {} epochs, learning rate 2e-4",
                    self.lora_rank(),
                    2 * self.lora_rank(),
                    self.epochs()
                ),
            ],
            Kind::RunCode => vec![
                format!("unpacked {input} ({} bytes) into /work/code", self.given.input_bytes),
                format!("$ {}", self.param("COMMAND", "python main.py")),
                "Using device: cuda:0".to_owned(),
                format!("Loaded config, {RUN_CODE_BATCHES} batches to run"),
            ],
        }
    }

    /// The lines whose moment falls in `(from, to]` of a job that runs for `total`.
    pub(super) fn lines_between(&self, from: Duration, to: Duration, total: Duration) -> Vec<String> {
        let lines = self.schedule();
        let count = lines.len() as u128;
        let total = total.as_millis().max(1);
        lines
            .into_iter()
            .enumerate()
            .filter(|(i, _)| {
                // Spread evenly, the last a little before the end, so it's written before the outputs.
                let at = total * (*i as u128 + 1) / (count + 1);
                at > from.as_millis() && at <= to.as_millis()
            })
            .map(|(_, line)| line)
            .collect()
    }

    /// Every line the job's work prints, in order, across its whole duration.
    fn schedule(&self) -> Vec<String> {
        match self.kind {
            Kind::FineTune => {
                let per_epoch = self.steps_per_epoch();
                let epochs = self.epochs();
                let mut lines = Vec::new();
                for step in 1..=per_epoch * epochs {
                    let epoch = (step - 1) / per_epoch + 1;
                    lines.push(format!(
                        "epoch {epoch}/{epochs} step {step}/{} loss {:.4} lr 2.0e-04 grad_norm {:.3}",
                        per_epoch * epochs,
                        self.loss(step),
                        0.4 + self.noise(step, 3) * 0.3
                    ));
                    if step % per_epoch == 0 {
                        let first = step - per_epoch + 1;
                        let mean = (first..=step).map(|s| self.loss(s)).sum::<f64>() / real(per_epoch);
                        lines.push(format!("epoch {epoch} done: mean loss {mean:.4}"));
                    }
                }
                lines.push("saving the adapter: adapter_model.safetensors".to_owned());
                lines
            }
            Kind::RunCode => {
                let mut lines: Vec<String> = (1..=RUN_CODE_BATCHES)
                    .map(|batch| {
                        format!(
                            "batch {batch}/{RUN_CODE_BATCHES}: {:.2} s, {:.0} items/s, gpu memory {:.1} GB",
                            0.8 + self.noise(batch, 1) * 0.3,
                            1_150.0 + self.noise(batch, 2) * 200.0,
                            3.1 + self.noise(batch, 4) * 0.4
                        )
                    })
                    .collect();
                lines.push("writing outputs/result.txt".to_owned());
                lines.push("Done.".to_owned());
                lines
            }
        }
    }

    /// The files the job leaves in its outputs, by their path in the outputs folder.
    pub(super) fn outputs(&self) -> Vec<(String, Vec<u8>)> {
        match self.kind {
            Kind::FineTune => vec![
                ("adapter_model.safetensors".to_owned(), self.adapter()),
                ("training_log.json".to_owned(), self.training_log()),
            ],
            Kind::RunCode => vec![("result.txt".to_owned(), self.run_result().into_bytes())],
        }
    }

    /// A number from the seed, step and stream: the same for the same session every time.
    fn draw(&self, step: u64, stream: u8) -> u32 {
        let mut hasher = Sha256::new();
        hasher.update(self.seed);
        hasher.update(step.to_le_bytes());
        hasher.update([stream]);
        let digest = hasher.finalize();
        u32::from_le_bytes([digest[0], digest[1], digest[2], digest[3]])
    }

    /// [`Self::draw`] as a number in `[0, 1)`.
    fn noise(&self, step: u64, stream: u8) -> f64 {
        f64::from(self.draw(step, stream)) / 4_294_967_296.0
    }

    /// Generated bytes from the seed, as many as asked for.
    fn bytes(&self, label: &str, len: usize) -> Vec<u8> {
        let mut out = Vec::with_capacity(len);
        let mut block = 0_u64;
        while out.len() < len {
            let mut hasher = Sha256::new();
            hasher.update(self.seed);
            hasher.update(label.as_bytes());
            hasher.update(block.to_le_bytes());
            out.extend_from_slice(&hasher.finalize());
            block += 1;
        }
        out.truncate(len);
        out
    }

    fn epochs(&self) -> u64 {
        self.number("EPOCHS", 2, 1, 5)
    }

    fn lora_rank(&self) -> u64 {
        self.number("LORA_RANK", 16, 1, 64)
    }

    fn steps_per_epoch(&self) -> u64 {
        self.given.input_lines.div_ceil(8).clamp(4, MAX_STEPS_PER_EPOCH)
    }

    /// Training loss at a step: falling fast, then flattening, with a little noise.
    fn loss(&self, step: u64) -> f64 {
        let progress = real(step) / real(self.steps_per_epoch() * self.epochs());
        0.42 + 1.9 * (-3.0 * progress).exp() + (self.noise(step, 0) - 0.5) * 0.06
    }

    /// A `LoRA` adapter in the safetensors format: a little-endian header length, a JSON header naming each
    /// tensor's type, shape and byte range, then the tensors' bytes (generated, F32).
    fn adapter(&self) -> Vec<u8> {
        let rank = usize::try_from(self.lora_rank()).unwrap_or(16);
        let mut header = serde_json::Map::new();
        header.insert(
            "__metadata__".to_owned(),
            serde_json::json!({
                "format": "pt",
                "base_model": self.param("BASE_MODEL", "Qwen2.5 0.5B Instruct"),
                "lora_rank": rank.to_string(),
                "simulated": "true",
            }),
        );
        let mut data = Vec::new();
        for layer in 0..2 {
            for projection in ["q_proj", "v_proj"] {
                for (matrix, shape) in [("lora_A", [rank, HIDDEN]), ("lora_B", [HIDDEN, rank])] {
                    let name = format!("base_model.model.layers.{layer}.self_attn.{projection}.{matrix}.weight");
                    let floats: Vec<u8> = self
                        .bytes(&name, shape[0] * shape[1] * 2)
                        .as_chunks::<2>()
                        .0
                        .iter()
                        .flat_map(|pair| {
                            // Small weights around zero, as a freshly trained adapter's are.
                            let value = (f32::from(u16::from_le_bytes(*pair)) / 65_535.0 - 0.5) * 0.04;
                            value.to_le_bytes()
                        })
                        .collect();
                    header.insert(
                        name,
                        serde_json::json!({
                            "dtype": "F32",
                            "shape": shape,
                            "data_offsets": [data.len(), data.len() + floats.len()],
                        }),
                    );
                    data.extend_from_slice(&floats);
                }
            }
        }
        let mut header = serde_json::to_vec(&header).expect("the header serialises");
        // The header is padded with spaces to a multiple of 8, as safetensors writers do.
        header.resize(header.len().div_ceil(8) * 8, b' ');
        let mut file = Vec::with_capacity(8 + header.len() + data.len());
        file.extend_from_slice(&(header.len() as u64).to_le_bytes());
        file.extend_from_slice(&header);
        file.extend_from_slice(&data);
        file
    }

    fn training_log(&self) -> Vec<u8> {
        let per_epoch = self.steps_per_epoch();
        let steps: Vec<_> = (1..=per_epoch * self.epochs())
            .map(|step| {
                serde_json::json!({
                    "step": step,
                    "epoch": (step - 1) / per_epoch + 1,
                    "loss": (self.loss(step) * 10_000.0).round() / 10_000.0,
                })
            })
            .collect();
        let log = serde_json::json!({
            "base_model": self.param("BASE_MODEL", "Qwen2.5 0.5B Instruct"),
            "epochs": self.epochs(),
            "lora_rank": self.lora_rank(),
            "training_examples": self.given.input_lines,
            "steps": steps,
            "final_loss": (self.loss(per_epoch * self.epochs()) * 10_000.0).round() / 10_000.0,
            "simulated": true,
        });
        serde_json::to_vec_pretty(&log).expect("the log serialises")
    }

    fn run_result(&self) -> String {
        let mut text = format!("$ {}\n", self.param("COMMAND", "python main.py"));
        let mut total = 0.0;
        for batch in 1..=RUN_CODE_BATCHES {
            let accuracy = 0.61 + 0.3 * (real(batch) / real(RUN_CODE_BATCHES)) + self.noise(batch, 5) * 0.02;
            total += accuracy;
            let _ = writeln!(text, "batch {batch}: accuracy {accuracy:.3}");
        }
        let _ = writeln!(text, "mean accuracy {:.3} over {RUN_CODE_BATCHES} batches", total / real(RUN_CODE_BATCHES));
        text.push_str("exit code 0\n(simulated by the development runner: your code wasn't run)\n");
        text
    }
}

/// A count as a real number; every count here is far below 2^32.
fn real(count: u64) -> f64 {
    f64::from(u32::try_from(count).unwrap_or(u32::MAX))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn simulation(kind: Kind, params: &[(&str, &str)], input_lines: u64) -> Simulation {
        let given = Given {
            params: params.iter().map(|&(name, value)| (format!("SESSION_PARAM_{name}"), value.to_owned())).collect(),
            input_name: Some("given".to_owned()),
            input_bytes: 1_000,
            input_lines,
        };
        Simulation::new(kind, given, "01a11d3e-443d-77f5-b801-ca8c40f876a3")
    }

    #[test]
    fn a_resumed_attempt_carries_on_where_the_last_one_stopped() {
        let total = Duration::from_secs(90);
        for kind in [Kind::FineTune, Kind::RunCode] {
            let job = simulation(kind, &[], 100);
            let whole = job.lines_between(Duration::ZERO, total, total);
            let mut pieces = job.lines_between(Duration::ZERO, Duration::from_millis(37_250), total);
            pieces.extend(job.lines_between(Duration::from_millis(37_250), total, total));
            assert_eq!(whole, job.schedule(), "{kind:?}: every line, once");
            assert_eq!(pieces, whole, "{kind:?}: no line lost or repeated at the checkpoint");
        }
    }

    #[test]
    fn the_loss_falls() {
        let job = simulation(Kind::FineTune, &[("EPOCHS", "2")], 200);
        let steps = job.steps_per_epoch() * 2;
        assert!(job.loss(steps) < job.loss(1) - 1.0, "{} to {}", job.loss(1), job.loss(steps));
        assert!(job.loss(steps) > 0.3);
    }

    #[test]
    fn the_adapter_is_a_valid_safetensors_file() {
        let adapter = simulation(Kind::FineTune, &[("LORA_RANK", "32")], 50).adapter();
        let length = usize::try_from(u64::from_le_bytes(adapter[..8].try_into().unwrap())).unwrap();
        assert_eq!(length % 8, 0);
        let header: serde_json::Value = serde_json::from_slice(&adapter[8..8 + length]).unwrap();
        let data = adapter.len() - 8 - length;
        let mut ends: Vec<u64> = header
            .as_object()
            .unwrap()
            .iter()
            .filter(|(name, _)| *name != "__metadata__")
            .map(|(_, tensor)| {
                let shape: Vec<u64> = serde_json::from_value(tensor["shape"].clone()).unwrap();
                let offsets: [u64; 2] = serde_json::from_value(tensor["data_offsets"].clone()).unwrap();
                assert_eq!(offsets[1] - offsets[0], shape.iter().product::<u64>() * 4, "F32: 4 bytes a value");
                assert!(shape.contains(&32), "rank 32");
                offsets[1]
            })
            .collect();
        ends.sort_unstable();
        assert_eq!(ends.len(), 8);
        assert_eq!(ends.last().copied(), Some(data as u64), "the tensors fill the data exactly");
        assert_eq!(header["__metadata__"]["simulated"], "true");
    }

    #[test]
    fn the_same_session_gets_the_same_outputs() {
        let job = simulation(Kind::FineTune, &[], 40);
        assert_eq!(job.outputs(), job.outputs());
        let other = Simulation::new(Kind::FineTune, job.given.clone(), "01a11d3e-443d-77f5-b801-ca8c40f876a4");
        assert_ne!(job.adapter(), other.adapter(), "each session its own weights");
    }
}
