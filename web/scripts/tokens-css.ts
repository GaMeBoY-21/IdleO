// Writes src/design/tokens.gen.css, Tailwind's theme and the fonts, from src/design/tokens.ts (web/DESIGN.md). Tailwind's
// own palette, spacing steps and sizes are cleared first, so only our tokens exist as classes. Both builds (the app and
// the website) import the one file. The default is Night Shift; Day Shift is the device's choice when it asks for light,
// and the `data-theme` attribute on <html> overrides either (src/design/theme.ts).
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import {
  displayScale,
  fonts,
  layout,
  motion,
  radii,
  shadows,
  spacing,
  headingFrom,
  headingStyle,
  plainSizes,
  themes,
  typeScale,
} from "../src/design/tokens.ts";

const px = (value: number) => (value === 0 ? "0px" : `${value / 16}rem`);
const vars = (theme: Record<string, string>, indent = "  ") =>
  Object.entries(theme)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join("\n");
const num = (value: number) => String(Math.round(value * 1000) / 1000);

const face = (family: string, file: string, weight: string, range: string, display = "swap") => `@font-face {
  font-family: "${family}";
  src: url("/fonts/${file}") format("woff2");
  font-weight: ${weight};
  font-style: normal;
  font-display: ${display};
  unicode-range: ${range};
}`;
const faces = Object.values(fonts)
  .flatMap((font) => [
    face(font.family, font.file, font.weight, font.range, font.display),
    ...(font.more ? [face(font.family, font.more.file, font.weight, font.more.range, font.display)] : []),
  ])
  .join("\n\n");
const fallbacks = Object.values(fonts)
  .flatMap((font) =>
    font.fallback
      ? [
          `@font-face {
  font-family: "${font.family} Fallback";
  src: local("Arial");
  size-adjust: ${font.fallback[0]}%;
  ascent-override: ${font.fallback[1]}%;
  descent-override: ${font.fallback[2]}%;
  line-gap-override: 0%;
}`,
        ]
      : [],
  )
  .join("\n\n");
const stack = (font: (typeof fonts)[keyof typeof fonts], rest: string) =>
  `"${font.family}", ${font.fallback ? `"${font.family} Fallback", ` : ""}${rest}`;

const display = Object.entries(displayScale)
  .map(([name, [min, vw, max, lineHeight, face]]) => {
    const size = min === max ? px(min) : `clamp(${px(min)}, ${num(vw)}vw, ${px(max)})`;
    const spacingEm = name === "display-wordmark" ? "-0.04em" : "-0.02em";
    return `  --text-${name}: ${size};
  --text-${name}--line-height: ${lineHeight};
  --text-${name}--letter-spacing: ${spacingEm};
  --text-${name}--font-weight: ${face === "display" ? 900 : 800};`;
  })
  .join("\n");

const css = `/* Generated by scripts/tokens-css.ts from src/design/tokens.ts. Don't edit. */
${faces}

${fallbacks}

:root {
${vars(themes.dark)}
  --shadow-glow-value: ${shadows.glow};
  color-scheme: dark;
}
@media (prefers-color-scheme: light) {
  :root:not([data-theme="dark"]) {
${vars(themes.light, "    ")}
    color-scheme: light;
  }
}
:root[data-theme="light"] {
${vars(themes.light)}
  color-scheme: light;
}

/* A night tile, and anything marked scope-night (the website's hero card and its sealed band), is Night Shift's dark
   whatever the page's theme, so everything inside it takes the dark colours. */
[data-tile="night"] {
${vars(themes.dark)}
  color-scheme: dark;
}
@utility scope-night {
${vars(themes.dark)}
  color-scheme: dark;
}

@theme {
  --color-*: initial;
  --spacing-*: initial;
  --spacing: initial;
  --text-*: initial;
  --radius-*: initial;
  --shadow-*: initial;
  --inset-shadow-*: initial;
  --drop-shadow-*: initial;
  --breakpoint-*: initial;
  --container-*: initial;
  --ease-*: initial;
  --animate-*: initial;
  --font-*: initial;
  --font-weight-*: initial;
  --blur-*: initial;

  --font-sans: ${stack(fonts.sans, "ui-sans-serif, system-ui, sans-serif")};
  --font-display: ${stack(fonts.display, "Arial, sans-serif")};
  --font-title: ${stack(fonts.title, "Arial, sans-serif")};
  --font-mono: ${stack(fonts.mono, 'ui-monospace, "SF Mono", Menlo, Consolas, monospace')};
${Object.entries(spacing)
  .map(([step, value]) => `  --spacing-${step.replace(".", "\\.")}: ${px(value)};`)
  .join("\n")}
${Object.entries(typeScale)
  .map(
    ([name, [size, lineHeight]]) =>
      `  --text-${name}: ${px(size)};\n  --text-${name}--line-height: ${px(lineHeight)};` +
      (size >= headingFrom && !plainSizes.has(name)
        ? `\n  --text-${name}--letter-spacing: ${headingStyle(size).letterSpacing};\n  --text-${name}--font-weight: ${headingStyle(size).weight};`
        : ""),
  )
  .join("\n")}
${display}
  --font-weight-regular: 400;
  --font-weight-medium: 500;
  --font-weight-semibold: 600;
  --font-weight-bold: 700;
${Object.entries(radii)
  .map(([name, value]) => `  --radius-${name}: ${value}px;`)
  .join("\n")}
  --breakpoint-md: ${px(layout.breakpoints.md)};
  --breakpoint-xl: ${px(layout.breakpoints.xl)};
  --breakpoint-2xl: ${px(layout.breakpoints["2xl"])};
  --container-rail-lg: ${px(layout.railLg)};
  --container-rail-sm: ${px(layout.railSm)};
  --container-prose: ${layout.prose};
  --container-rail: ${px(layout.rail)};
  --container-card: ${px(layout.card)};
  --container-form: ${px(layout.form)};
  --container-request: ${px(layout.request)};
  --container-content: ${px(layout.content)};
  --container-site: ${px(layout.site)};
  --container-lede: ${px(layout.lede)};
  --container-menu: ${px(layout.menu)};
  --container-narrow: ${px(layout.narrow)};
  --container-price: ${px(layout.price)};
  --container-amount: ${layout.amount};
  --ease-enter: ${motion.easing.enter};
  --ease-leave: ${motion.easing.leave};
  --default-transition-duration: ${motion.durations.press}ms;
  --default-transition-timing-function: ${motion.easing.enter};
  --animate-pulse: idleo-pulse ${motion.pulse}ms ease-in-out infinite;
  --animate-breathe: idleo-breathe ${motion.pulse}ms ease-in-out infinite;
  --animate-marquee: idleo-marquee ${motion.marquee}ms linear infinite;
}

@theme inline {
${Object.keys(themes.dark)
  .map((name) => `  --color-${name}: var(--${name});`)
  .join("\n")}
  --shadow-glow: var(--shadow-glow-value);
}
`;

writeFileSync(fileURLToPath(new URL("../src/design/tokens.gen.css", import.meta.url)), css);
